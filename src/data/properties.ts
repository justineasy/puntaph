export function getStay(id: string | undefined): Stay | undefined {
  return STAYS.find((s) => s.id === id)
}

export function byDestination(dest: string): Stay[] {
  return STAYS.filter((s) => s.destination === dest)
}

export function featured(count: number): Stay[] {
  const picks = STAYS.filter((s) => s.guestFavorite)
  const rest = STAYS.filter((s) => !s.guestFavorite)
  return [...picks, ...rest].slice(0, count)
}

export function priceBounds(): { min: number; max: number } {
  let min = Infinity
  let max = 0
  for (const s of STAYS) {
    if (s.price < min) min = s.price
    if (s.price > max) max = s.price
  }
  return { min, max }
}
